def format_video_line(video) -> str:
    """영상 한 줄. 토큰을 아끼려고 꼭 필요한 것만 넣는다.

    설명(description)은 넣지 않는다 — 대부분 링크와 해시태그라 분류에 도움이
    안 되면서 토큰만 크게 먹는다. 제목·채널·길이·카테고리로 충분하다.
    """
    minutes = video.duration_sec // 60
    length = f"{minutes}분" if minutes else f"{video.duration_sec}초"
    return f"[{video.video_id}] {video.title} — {video.channel_title} ({length})"
