function sjFont(fs) { return `bold ${fs}px "Pretendard", system-ui, -apple-system, "Segoe UI", sans-serif`; }
function sjSentence(g, c, pre, blank, post, cx, cy, bc) {
  let fs = 38;
  const full = pre + blank + post;
  c.font = sjFont(fs);
  while (fs > 18 && c.measureText(full).width > 700) { fs--; c.font = sjFont(fs); }
  const wPre = c.measureText(pre).width, wB = c.measureText(blank).width, wAll = c.measureText(full).width;
  let x = cx - wAll / 2;
  g.text(pre, x, cy, fs, '#1f2937', 'left'); x += wPre;
  g.rrect(x - 6, cy - fs * 0.7, wB + 12, fs * 1.4, 10, 'rgba(34,197,94,.15)', bc, 2);
  g.text(blank, x, cy, fs, bc, 'left'); x += wB;
  g.text(post, x, cy, fs, '#1f2937', 'left');
}
function optRect(i) { return [160 + i * 400, 320, 360, 200]; }
function nextQ(g) {
  const q = SJ_LIST[S.order[S.qi++]];
  S.q = { ...q, opts: Math.random() < 0.5 ? [q.ok, q.bad] : [q.bad, q.ok] };
  S.tmax = Math.max(3.5, 9 - (S.level - 1) * 0.6); S.t = S.tmax;
  S.picked = -1; S.res = null; S.timeout = false;
}
function answer(g, i) {
  S.picked = i;
  const right = i >= 0 && S.q.opts[i] === S.q.ok;
  S.res = right; S.timeout = i < 0; S.king = 1.2;
  if (right) {
    S.ok++; S.combo++; S.maxCombo = Math.max(S.maxCombo, S.combo);
    const pts = Math.round((60 + (S.t / S.tmax) * 80) * (1 + (S.level - 1) * 0.25) + S.combo * 8);
    const [x, y, w] = optRect(i);
    g.add(pts, x + w / 2, y - 10);
    g.sfx.coin(); g.burst(x + w / 2, y + 100, ['#22c55e', '#fde047', '#fff'], 18, 260);
    S.bg = 0.25; S.lock = S.lockMax = 1.1;
    if (S.combo % 10 === 0) { g.float(480, 300, `👑 ${S.combo}연속! 세종대왕님 감동`, '#ca8a04', 34); g.sfx.power(); g.shake(3); }
    if (S.ok % 10 === 0) {
      S.level++;
      g.later(() => { g.float(480, 260, `⬆ 레벨 ${S.level}! 시간이 줄어요`, '#15803d', 36); g.sfx.win(); }, 0.2);
      if (S.level % 3 === 0 && S.lives < 3) { S.lives++; g.later(() => g.float(480, 320, '💚 생명 +1', '#16a34a', 30), 0.6); }
    }
  } else {
    S.lives--; S.combo = 0; S.wrongList.push(S.q.ok);
    g.sfx.hit(); g.shake(7);
    S.bg = 0.4; S.lock = S.lockMax = 3.2;
  }
}
