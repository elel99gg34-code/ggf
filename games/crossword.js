function palRect(i) { return { x: CW_GX + i * 64, y: 640, w: 58, h: 52 }; }
function wrap(g, s, maxW, size) {
  const c = g.ctx; c.font = `500 ${size}px sans-serif`;
  const out = []; let cur = '';
  for (const ch of s) { if (c.measureText(cur + ch).width > maxW) { out.push(cur); cur = ch; } else cur += ch; }
  if (cur) out.push(cur);
  return out;
}
function cellsOf(w) { const o = []; for (let i = 0; i < w.len; i++) o.push(w.dir === 'across' ? [w.x + i, w.y] : [w.x, w.y + i]); return o; }
function generate(target) {
  const pool = U.shuffle(CW_WORDS.filter((p) => !S.used.has(p[0]) && [...p[0]].length <= 5).map((p) => ({ w: [...p[0]], clue: p[1], raw: p[0] })));
  const grid = U.grid(CW_N, CW_N, ''), dirOf = U.grid(CW_N, CW_N, 0);
  const placed = [];
  const first = pool.find((p) => p.w.length >= 3) || pool[0];
  const sx = Math.floor((CW_N - first.w.length) / 2), sy = Math.floor(CW_N / 2);
  put(first, sx, sy, 'across');
  function put(p, x, y, dir) {
    p.w.forEach((ch, i) => { const cx = dir === 'across' ? x + i : x, cy = dir === 'across' ? y : y + i; grid[cy][cx] = ch; dirOf[cy][cx] |= dir === 'across' ? 1 : 2; });
    placed.push({ w: p.w, clue: p.clue, raw: p.raw, x, y, dir, len: p.w.length });
  }
  const at = (x, y) => (x < 0 || y < 0 || x >= CW_N || y >= CW_N ? '' : grid[y][x]);
  function can(p, x, y, dir) {
    const L = p.w.length, dx = dir === 'across' ? 1 : 0, dy = 1 - dx;
    const ex = x + dx * (L - 1), ey = y + dy * (L - 1);
    if (x < 0 || y < 0 || ex >= CW_N || ey >= CW_N) return -1;
    if (at(x - dx, y - dy) || at(ex + dx, ey + dy)) return -1;
    let cross = 0;
    for (let i = 0; i < L; i++) {
      const cx = x + dx * i, cy = y + dy * i, v = grid[cy][cx];
      if (v) {
        if (v !== p.w[i]) return -1;
        if (dirOf[cy][cx] & (dir === 'across' ? 1 : 2)) return -1;
        cross++;
      } else if (at(cx + dy, cy + dx) || at(cx - dy, cy - dx)) return -1;
    }
    return cross;
  }
  for (const p of pool) {
    if (placed.length >= target) break;
    if (placed.some((q) => q.raw === p.raw)) continue;
    const opts = [];
    for (let i = 0; i < p.w.length; i++) for (let y = 0; y < CW_N; y++) for (let x = 0; x < CW_N; x++) {
      if (grid[y][x] !== p.w[i]) continue;
      for (const dir of ['across', 'down']) {
        const px = dir === 'across' ? x - i : x, py = dir === 'across' ? y : y - i;
        const cr = can(p, px, py, dir);
        if (cr > 0) opts.push({ x: px, y: py, dir, cr });
      }
    }
    if (!opts.length) continue;
    opts.sort((a, b) => b.cr - a.cr + (Math.random() - 0.5));
    put(p, opts[0].x, opts[0].y, opts[0].dir);
  }
  return { grid, placed };
}
function newPuzzle(g) {
  const target = Math.min(12, 6 + S.stage);
  let best = null;
  for (let k = 0; k < 25; k++) { const r = generate(target); if (!best || r.placed.length > best.placed.length) best = r; if (r.placed.length >= target) break; }
  if (best.placed.length < 4) { S.used.clear(); best = generate(target); }
  best.placed.forEach((w) => S.used.add(w.raw));
  if (S.used.size > CW_WORDS.length - 40) S.used.clear();
  S.sol = best.grid;
  S.words = best.placed;
  // 번호 매기기
  S.num = U.grid(CW_N, CW_N, 0);
  let n = 0;
  for (let y = 0; y < CW_N; y++) for (let x = 0; x < CW_N; x++) {
    const ws = S.words.filter((w) => w.x === x && w.y === y);
    if (ws.length) { n++; S.num[y][x] = n; ws.forEach((w) => (w.n = n)); }
  }
  S.words.sort((a, b) => (a.dir === b.dir ? a.n - b.n : a.dir === 'across' ? -1 : 1));
  // 격자 중앙 정렬
  let minX = CW_N, maxX = 0, minY = CW_N, maxY = 0;
  for (let y = 0; y < CW_N; y++) for (let x = 0; x < CW_N; x++) if (S.sol[y][x]) { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); }
  S.ox = CW_GX + (CW_N * CW_CS - (maxX - minX + 1) * CW_CS) / 2 - minX * CW_CS;
  S.oy = CW_GY + (CW_N * CW_CS * 0.86 - (maxY - minY + 1) * CW_CS) / 2 - minY * CW_CS;
  S.oy = Math.max(CW_GY - minY * CW_CS, S.oy);
  S.inp = U.grid(CW_N, CW_N, ''); S.lock = U.grid(CW_N, CW_N, false); S.revealed = U.grid(CW_N, CW_N, false);
  S.cur = 0; S.curCell = null; S.time = 0; S.nextT = 0; S.wrongT = 0; S.clueRects = [];
  S.hints = Math.max(S.hints, 2);
  selectWord(0);
  S.msg = `퍼즐 ${S.stage} — 낱말 ${S.words.length}개`; S.msgT = 1.6;
}
function selectWord(i, x, y) {
  if (i < 0 || !S.words[i]) return;
  S.cur = i;
  const w = S.words[i], cs = cellsOf(w);
  if (x !== undefined) S.curCell = [x, y];
  else S.curCell = cs.find(([a, b]) => !S.inp[b][a]) || cs[0];
  buildPalette();
}
function buildPalette() {
  const w = S.words[S.cur];
  const set = new Set(w.w);
  // 교차 낱말 글자도 일부 포함
  const extra = U.shuffle([...CW_FILL]);
  for (const ch of extra) { if (set.size >= 12) break; set.add(ch); }
  S.pal = U.shuffle([...set]).slice(0, 12);
  for (const ch of w.w) if (!S.pal.includes(ch)) S.pal[U.randi(0, 11)] = ch;
}
function nextOpen(d) {
  const n = S.words.length;
  for (let k = 1; k <= n; k++) { const i = (S.cur + d * k + n * 2) % n; if (!S.words[i].done) return i; }
  return S.cur;
}
function typeChar(g, ch) {
  const w = S.words[S.cur]; if (!w || w.done || !S.curCell) return;
  const [x, y] = S.curCell;
  if (S.lock[y][x]) {
    const free = cellsOf(w).find(([a, b]) => !S.lock[b][a] && !S.inp[b][a]) || cellsOf(w).find(([a, b]) => !S.lock[b][a]);
    if (!free) return;
    S.curCell = free; return typeChar(g, ch);
  }
  S.inp[y][x] = ch;
  g.sfx.tone(600, 0.04, 'square', 0.04);
  advance();
  checkWord(g, w);
}
function advance() {
  const w = S.words[S.cur], cs = cellsOf(w);
  const i = cs.findIndex(([a, b]) => a === S.curCell[0] && b === S.curCell[1]);
  for (let k = i + 1; k < cs.length; k++) if (!S.lock[cs[k][1]][cs[k][0]]) { S.curCell = cs[k]; return; }
  const empty = cs.find(([a, b]) => !S.inp[b][a]);
  if (empty) S.curCell = empty;
}
function erase(g) {
  const w = S.words[S.cur]; if (!w || !S.curCell) return;
  const cs = cellsOf(w);
  let i = cs.findIndex(([a, b]) => a === S.curCell[0] && b === S.curCell[1]);
  if (!S.inp[S.curCell[1]][S.curCell[0]] || S.lock[S.curCell[1]][S.curCell[0]]) {
    for (let k = i - 1; k >= 0; k--) if (!S.lock[cs[k][1]][cs[k][0]]) { i = k; break; }
  }
  const [x, y] = cs[i];
  if (!S.lock[y][x]) { S.inp[y][x] = ''; S.curCell = [x, y]; g.sfx.click(); }
}
function checkWord(g, w) {
  const cs = cellsOf(w);
  if (cs.some(([a, b]) => !S.inp[b][a])) return;
  const ok = cs.every(([a, b], i) => S.inp[b][a] === w.w[i]);
  if (ok) {
    w.done = true;
    cs.forEach(([a, b]) => (S.lock[b][a] = true));
    const pts = w.len * 100 * S.stage;
    const [a, b] = cs[Math.floor(cs.length / 2)];
    g.add(pts, S.ox + a * CW_CS + CW_CS / 2, S.oy + b * CW_CS);
    g.sfx.coin();
    cs.forEach(([a2, b2]) => g.burst(S.ox + a2 * CW_CS + CW_CS / 2, S.oy + b2 * CW_CS + CW_CS / 2, ['#84cc16', '#fde047', '#fff'], 6, 150, 0.5, 4));
    // 교차로 자동 완성된 낱말 확인
    for (const o of S.words) if (!o.done && cellsOf(o).every(([x, y], i) => S.inp[y][x] === o.w[i])) { o.done = true; cellsOf(o).forEach(([x, y]) => (S.lock[y][x] = true)); g.add(o.len * 100 * S.stage); }
    if (S.words.every((o) => o.done)) {
      const bonus = Math.max(0, Math.round(600 - S.time * 3)) * S.stage + S.hearts * 200;
      g.add(bonus);
      S.msg = `퍼즐 완성! 보너스 +${bonus}`; S.msgT = 2.4; S.nextT = 2.4;
      S.hearts = Math.min(5, S.hearts + 1); S.hints++;
      g.sfx.win(); g.shake(5, 0.3); g.burst(300, 330, ['#f59e0b', '#84cc16', '#ec4899', '#38bdf8'], 80, 450, 1.3, 6);
    } else selectWord(nextOpen(1));
  } else {
    S.hearts--; S.wrongT = 0.6;
    g.sfx.hit(); g.shake(6, 0.25);
    cs.forEach(([a, b]) => { if (!S.lock[b][a]) S.inp[b][a] = ''; });
    S.curCell = cs.find(([a, b]) => !S.lock[b][a]) || cs[0];
    S.msg = '틀렸어요! ❤️ -1'; S.msgT = 1.2;
    if (S.hearts <= 0) g.later(() => g.over(`퍼즐 ${S.stage}에서 하트 소진`), 0.5);
  }
}
function useHint(g) {
  const w = S.words[S.cur]; if (!w || w.done) return;
  if (S.hints <= 0) { g.sfx.beep(150, 0.08); S.msg = '힌트가 없어요'; S.msgT = 1; return; }
  const cs = cellsOf(w), cand = cs.map((p, i) => [p, i]).filter(([[a, b], i]) => S.inp[b][a] !== w.w[i]);
  if (!cand.length) return;
  const [[a, b], i] = U.choice(cand);
  S.hints--;
  S.inp[b][a] = w.w[i]; S.lock[b][a] = true; S.revealed[b][a] = true;
  g.sfx.power();
  advance();
  checkWord(g, w);
}
