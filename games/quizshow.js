function wrap(g, s, maxW, size) {
  const c = g.ctx; c.font = `bold ${size}px sans-serif`;
  const out = []; let cur = '';
  for (const ch of s) { if (c.measureText(cur + ch).width > maxW && ch !== ' ') { out.push(cur); cur = ch; } else cur += ch; }
  if (cur) out.push(cur);
  return out;
}
