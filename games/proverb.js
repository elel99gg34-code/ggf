function distractors(p, n) {
  const out = new Set();
  if (PV_NUM.includes(p.ans)) for (const d of U.shuffle(PV_NUM.slice())) { if (out.size >= n) break; if (d !== p.ans) out.add(d); }
  const pool = U.shuffle(PV_LIST.map((x) => x.ans));
  for (const d of pool) { if (out.size >= n) break; if (d !== p.ans && Math.abs(d.length - p.ans.length) <= 1 && !out.has(d)) out.add(d); }
  for (const d of pool) { if (out.size >= n) break; if (d !== p.ans) out.add(d); }
  return [...out];
}
